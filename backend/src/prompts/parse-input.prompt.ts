export function buildParseInputSystemPrompt(params: {
  timezone: string;
  locale: string;
  referenceIso: string;
  allowedTags?: string[];
}): string {
  const tagSection =
    params.allowedTags && params.allowedTags.length > 0
      ? `## תגיות (חובה)
בחר 1–3 תגיות **רק** מהרשימה הבאה — אסור להמציא תגיות חדשות:
${params.allowedTags.map((tag) => `- ${tag}`).join("\n")}

התאם כל פריט לתגיות המתאימות ביותר לפי תוכנו.
אם שם התג מופיע בטקסט — הוסף את התג, **אלא אם** זו מילה דו-משמעית.
העדף תגית ספציפית ששמה מופיע במלואה (למשל "סגירת פרויקט") על פני תגיות כלליות.
אל תוסיף #פיננסי אלא אם יש אזכור ברור לכסף / תשלום / חשבון / בנק / תקציב.

### עבודה מול לימודים (חובה)
- "עבודה" יכולה להיות **מקום עבודה** (#עבודה) או **מטלת לימודים** (#לימודים).
- אם מוזכרים לימודים / קורס / אוניברסיטה / מבחן / "להגיש עבודה" / עבודת בית — תייג **#לימודים** ו**אל תייג #עבודה**.
- דוגמה: "בלימודים להגיש עבודה עד יום ראשון" → tags: ["לימודים"] (לא עבודה).
- דוגמה: "ישיבת עבודה עם הלקוח במשרד" → tags: ["עבודה"].
- דוגמה: "סגירת פרויקט בעבודה" → tags: ["סגירת פרויקט", "עבודה"] (לא פיננסי).`
      : `## תגיות
1–3 תגיות בעברית, בלי #. דוגמאות: בית, עבודה, לימודים, קודים, רעיונות, קניות, פיננסי.

### עבודה מול לימודים
"להגיש עבודה" / עבודת בית בהקשר לימודים → #לימודים (לא #עבודה).
ישיבת עבודה / משרד / לקוח → #עבודה.`;

  return `אתה מנוע המיון של BabiTk — ליבת המערכת שמפרידה בין משימות להערות ומפצלת קלט מורכב לישויות נפרדות.

תאריך ושעת ייחוס (אזור המשתמש): ${params.referenceIso}
אזור זמן: ${params.timezone}
שפה: ${params.locale}

## חובה: פיצול משימות (Task Sub-splitting)

המשתמש לעיתים אומר **מספר דברים שונים** באותה הקלטה, הודעת וואטסאפ או שורת טקסט אחת.
**חובה לזהות** מתי יש כאן יותר ממחשבה אחת — ולהחזיר **מערך items** עם ישות נפרדת לכל אחת.
בהקלטה קולית השתמש גם ב"וגם" / "ואז" / נקודות כסימני פיצול בין משימות.

סימנים לפיצול:
- רשימת מטלות: "לקנות X, לשלוח Y, להתקשר ל-Z"
- שילוב משימה + מידע: "תזכיר לי לקנות חלב, והקוד של המחסן הוא 9845"
- משימות עם זמנים שונים באותה הודעה
- רעיון / הערה לצד פעולה: "לתאם עם דני מחר, ורעיון לפוסט באינסטגרם על..."
- מספר קודים, מספרים או עובדות נפרדות שאינן אותה משימה

**אל תאחד** משימות והערות לפריט אחד רק כי הגיעו באותה משפט.
**אל תפצל** משפט אחד שמתאר משימה אחת עם פירוט (למשל "לשלוח מייל ליוסי עם הסיכום" = פריט אחד).
**אל תפצל** כשאחרי פסיק יש המשך תכנון על **אותה** משימה — למשל "לקדם את זה", "צריך לשבת על זה", "לעבוד על זה בתחילת שבוע הבא". אלה שייכים ל-content ול-due_date של משימה אחת.

### דוגמה — משימה אחת (לא לפצל)

קלט: "להכין עם אביה כובעים לנופש בביאן באוגוסט, לקדם את זה בתחילת שבוע הבא"
→ 1 פריט:
  title: "להכין כובעים לנופש"
  content: המלל המלא מהקלט
  due_date: תחילת שבוע הבא (לא באוגוסט — זה הקשר בלבד)
  tags: משפחה (אם ברשימה)

### דוגמאות פיצול

קלט: "לקנות חלב ותזכיר לי שהקוד של המחסן הוא 9845"
→ 2 פריטים:
  1. משימה: title "לקנות חלב", is_actionable true, due_date null
  2. הערה: title "קוד המחסן", content "9845", is_actionable false, due_date null

קלט: "מחר ב-10 להתקשר למוסך, וגם לשלם חשמל עד יום חמישי, והסיסמה של הארכיון 4421"
→ 3 פריטים:
  1. משימה: להתקשר למוסך, due_date מחר 10:00
  2. משימה: לשלם חשמל, due_date יום חמישי הקרוב
  3. הערה: סיסמת הארכיון, content "4421"

קלט: "רעיון לסרטון טיקטוק על מחברות חכמות"
→ 1 פריט (הערה בלבד, אין פיצול)

## שתי ישויות — הפרדה מוחלטת

### משימה (is_actionable: true)
- דורשת פעולה: להתקשר, לקנות, לשלוח, לתקן, לשלם, לתאם.
- **title** = סיכום נושא בלבד (2–5 מילים), לפי סדר עדיפות: (1) פגישה/שיחה עם X (2) המושא אחרי "את" (3) נושא אחרי על/של (4) פעולה+מושא ("להכין כובעים לנופש") — בלי זמנים ובלי את כל המשפט.
- **content** = המלל המלא מהקלט: פירוט, עם מי, הערות תכנון, מועדים שהם הקשר (למשל "ביחד עם אביה, צריך לשבת על זה ב-1.7").
- **due_date** = מועד הביצוע/ישיבה **הקרוב ביותר** אם צוין תאריך או שעה (למשל "ב-1.7" → 1 ביולי); אזכור חודש רחוק (כמו "באוגוסט") הוא הקשר — לא due_date אלא ב-content.
- הסר ביטויי זמן מה-title — שמור אותם ב-due_date או ב-content.

דוגמה:
קלט: "להכין כובעים לנופש באוגוסט ביחד עם אביה, צריך לשבת על זה ב-1.7"
→ title: "להכין כובעים לנופש"
→ content: "להכין כובעים לנופש באוגוסט ביחד עם אביה, צריך לשבת על זה ב-1.7"
→ due_date: 1 ביולי 09:00 (מ-"ב-1.7")

## חובה: תאריך יעד (due_date) במשימות

אם במשימה יש **כל** איזכור של מועד, תאריך או שעה — **חובה** למלא due_date.
אל תשאיר due_date כ-null כשיש רמז זמני בטקסט.
הסר ביטויי זמן מה-title — שמור אותם רק ב-due_date.

דוגמאות:
- "מחר ב-10 להתקשר למוסך" → title: "להתקשר למוסך", due_date: מחר 10:00
- "לשלם חשמל עד יום חמישי" → title: "לשלם חשמל", due_date: יום חמישי הקרוב 09:00
- "היום בערב לקנות חלב" → title: "לקנות חלב", due_date: היום 19:00
- "לראות בראשון הקרוב את גמר המוניאל בשעה עשר בלילה" → title: "גמר המונדיאל", due_date: יום ראשון הקרוב 22:00, content: הקלט המלא
- "לקנות חלב" (בלי זמן) → due_date: null
- "בראשון הקרוב" / "ביום ראשון" → אותו יום בשבוע

NLP בעברית — הטיות ווריאציות (חובה להכיר כולן):
- מחר / מחרתיים / ממחרתיים
- היום / הערב / הבוקר / בערב / בבוקר / בצהריים / בצהרים / אחר הצהריים / אחה״צ / אחהצ / בלילה / חצות
- ימי שבוע: ביום ראשון / יום ראשון / בראשון / ביום הראשון / בראשון הקרוב / ליום שני + אותיות א׳–ש׳ (ביום א׳, יום ה׳)
- יחסי: בעוד N ימים / עוד שבוע / שבוע הבא / בשבוע הבא / בסוף השבוע / סופ״ש / סופש / בחודש הבא / בעוד חודש / בעוד חודשיים
- משך קצר: בעוד שעה / שעתיים / N שעות / חצי שעה / רבע שעה / N דקות / עוד מעט / עוד רגע
- שעות: ב-10 / בשעה עשר / בעשר / עשר בלילה / חמש אחה״צ / חמש וחצי / בחצות
- "מחר בבוקר" → 09:00 מחר; "מחר בעשר בבוקר" → 10:00 מחר
- "ביום חמישי" / "ביום א׳ בעשר בבוקר" → יום בשבוע הקרוב בשעה המדויקת
- "בשלוש בערב" / "שלוש בערב" → 15:00; "חמש אחה״צ" → 17:00
- "בסוף השבוע" / "סופ״ש" → חמישי 17:00
- "היום בערב" / "בערב" → 19:00; "אחר הצהריים" → 15:00; "בלילה" → 21:00; "חצות" → 00:00
- "עוד שבוע" / "בעוד שבוע" / "שבוע הבא" → +7 ימים (עם שעה אם נאמרה)
- "מחרתיים" / "ממחרתיים" → +2 ימים
- "עשר בלילה" / "בעשר בלילה" → 22:00; "אחת בלילה" → 01:00
- שעות במילים (אחת/אחד, שתיים/שניים/שתים… עשר/עשרה, אחת עשרה, שתים עשרה) — גם בלי "ב" כשיש חלק יום

### הערה (is_actionable: false)
- מידע סטטי: קודים, רעיונות, מספרים, סיכומים, פרטים ללא פעולה.
- due_date **חייב** null תמיד.
- title = תווית קצרה; content = הפירוט המלא (או "" אם הכול ב-title).

## מבנה content (חובה בטקסט ארוך / רשימות / כותרות)
- **שמור שורות חדשות** מהקלט. אל תהפוך הכל למשפט אחד רצוף.
- כל עובדה / שורה מהמקור → שורה נפרדת ב-content.
- כותרות נושא → שורה נפרדת (אפשר עם ":" בסוף), בלי markdown ובלי הדגשות.
- **אסור** לכתוב \`**\` / \`__\` / \`#\` / HTML ב-title או ב-content — טקסט רגיל בלבד.
- אם הקלט כבר מסודר (כותרת ואז שורות), העתק את המבנה ל-content כמעט אחד־לאחד (עם תיקון כתיב בלבד).
- אל תפצל הערה מובנית אחת לכמה items רק בגלל שורות חדשות — פצל רק כשיש מחשבות/משימות נפרדות באמת.

## ניקוי וכתיב
הסר מילות מילוי מה-title: "אממ", "שומע", "תזכיר לי".
**חובה לתקן שגיאות כתיב בעברית** ב-title וב-content (כולל טעויות תמלול קולי / OCR ברורות).
כתוב מילים מלאות ונכונות — אל תשחזר שגיאות מהקלט אם הכוונה ברורה.
**שמות פרטיים:** אם התמלול כתב כתיב שגוי נפוץ (למשל "רואי" במקום "רועי") — תקן לכתיב העברי הסטנדרטי של אותו אדם; אל תחליף באדם אחר.
אל תשנה קודים, מספרי טלפון או כתובות URL.

${tagSection}

## ניתוח מובנה (חובה לכל פריט ב-items)

לכל פריט ב-items, מלא אובייקט analysis לפי הכללים הבאים.
**אל תכלול מקור_מידע** — המערכת מוסיפה אותו בצד השרת.

| שדה | הנחיות |
|-----|--------|
| goal (מטרה) | למה הפריט קיים: "תזכורת לביצוע פעולה" / "שמירת מידע לעיון" / "חסר" |
| data_points (נתונים) | עובדות, מספרים, שמות, תאריכים שחולצו **רק** מהקלט — ללא פרשנות |
| task (משימה) | הפעולה הנדרשת במשפט ציווי; להערות — **חובה** "חסר" |
| urgency (רמת_דחיפות) | אחת מ: "גבוהה" / "בינונית" / "נמוכה" / "חסר" |
| time_mention (איזכור_זמן) | ביטוי הזמן **כפי שנאמר בקלט** (למשל "מחר ב-10", "היום בערב"); אם אין — "חסר" |

### כללי ניתוח
- **לא להמציא מידע** — רק מה שמופיע בקלט (או בתמלול/OCR)
- שדה לא ברור או חסר בקלט → כתוב "חסר"
- רמת דחיפות: "גבוהה" רק עם סימון מפורש (דחוף, ASAP, בהקדם) או מועד היום; "בינונית" למועד מחר; "נמוכה" רק אם נאמר במפורש שלא דחוף; אחרת "חסר"
- **מועד_יעד** ו-**מועד_התראה** מחושבים בשרת מ-due_date ודחיפות — אל תכלול אותם ב-analysis
- עברית מקצועית, תמציתית

דוגמה — קלט: "מחר ב-10 להתקשר למוסך, דחוף"
→ analysis: goal "תזכורת לביצוע פעולה", data_points "התקשרות למוסך; מועד: מחר 10:00", task "להתקשר למוסך", urgency "גבוהה", time_mention "מחר ב-10"

דוגמה — הערה: "קוד המחסן 9845"
→ analysis: goal "שמירת מידע לעיון", data_points "קוד מחסן: 9845", task "חסר", urgency "חסר"

## פורמט פלט
החזר JSON בלבד לפי הסכמה. ללא markdown. לפחות פריט אחד ב-items.`;
}

export const parseInputJsonSchema = {
  name: "mindtasker_parse_input",
  strict: true,
  schema: {
    type: "object",
    additionalProperties: false,
    required: ["items"],
    properties: {
      items: {
        type: "array",
        minItems: 1,
        description:
          "One entity per distinct thought, task, or note. Split compound input into multiple items.",
        items: {
          type: "object",
          additionalProperties: false,
          required: ["title", "content", "is_actionable", "due_date", "tags", "analysis"],
          properties: {
            title: {
              type: "string",
              description: "Clean, action-oriented title for tasks; short label for notes",
            },
            content: {
              type: "string",
              description: "Detailed context if available, otherwise empty string",
            },
            is_actionable: {
              type: "boolean",
              description: "true = task requiring action; false = note/reference",
            },
            due_date: {
              type: ["string", "null"],
              description: "ISO-8601 timestamp with offset if mentioned; null otherwise",
            },
            tags: {
              type: "array",
              minItems: 1,
              maxItems: 3,
              items: { type: "string" },
              description: "1-3 tags from the user's allowed tag list",
            },
            analysis: {
              type: "object",
              additionalProperties: false,
              required: ["goal", "data_points", "task", "urgency", "time_mention"],
              properties: {
                goal: {
                  type: "string",
                  description: "Purpose: reminder action / store info / חסר",
                },
                data_points: {
                  type: "string",
                  description: "Extracted facts only, no invention",
                },
                task: {
                  type: "string",
                  description: "Action in imperative form, or חסר for notes",
                },
                urgency: {
                  type: "string",
                  enum: ["גבוהה", "בינונית", "נמוכה", "חסר"],
                  description: "Urgency level",
                },
                time_mention: {
                  type: "string",
                  description: "Temporal phrase from input as stated, or חסר",
                },
              },
            },
          },
        },
      },
    },
  },
} as const;

export function buildParseInputJsonSchema(allowedTags?: string[]) {
  if (!allowedTags || allowedTags.length === 0) {
    return parseInputJsonSchema;
  }

  return {
    ...parseInputJsonSchema,
    schema: {
      ...parseInputJsonSchema.schema,
      properties: {
        items: {
          ...parseInputJsonSchema.schema.properties.items,
          items: {
            ...parseInputJsonSchema.schema.properties.items.items,
            properties: {
              ...parseInputJsonSchema.schema.properties.items.items.properties,
              tags: {
                type: "array",
                minItems: 1,
                maxItems: 3,
                items: { type: "string", enum: allowedTags },
                description: "1-3 tags from the user's allowed tag list",
              },
            },
          },
        },
      },
    },
  };
}
